create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('owner','admin','scorekeeper')),
  created_at timestamptz not null default now()
);

create or replace function public.is_tournament_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists(select 1 from public.admin_users where user_id = auth.uid());
$$;

create table if not exists public.teams (
  id integer generated by default as identity primary key,
  name_en text not null,
  name_bn text,
  short_name text,
  logo_url text,
  manager_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  draw_position integer unique check (draw_position between 1 and 32)
);

create table if not exists public.matches (
  match_no integer primary key check (match_no between 1 and 31),
  match_date date not null,
  kickoff_time time not null default '20:00',
  round_key text not null check (round_key in ('round32','round16','quarter_final','semi_final','final')),
  status text not null default 'scheduled' check (status in ('scheduled','live','half_time','full_time','postponed')),
  team_a_id integer references public.teams(id) on delete set null,
  team_b_id integer references public.teams(id) on delete set null,
  score_a integer not null default 0 check (score_a >= 0),
  score_b integer not null default 0 check (score_b >= 0),
  minute integer not null default 0 check (minute between 0 and 150),
  venue text not null default 'M.K. Stadium, Daulatpur',
  winner_team_id integer references public.teams(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.match_events (
  id uuid primary key default gen_random_uuid(),
  match_no integer not null references public.matches(match_no) on delete cascade,
  team_id integer references public.teams(id) on delete set null,
  event_type text not null check (event_type in ('goal','yellow_card','red_card')),
  player_name text,
  minute integer not null default 0 check (minute between 0 and 150),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id uuid primary key default gen_random_uuid(),
  team_name text not null,
  manager_name text not null,
  phone text not null,
  email text,
  squad jsonb not null default '[]'::jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  admin_note text,
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_draws (
  id uuid primary key default gen_random_uuid(),
  draw_version integer not null,
  draw_data jsonb not null,
  method text not null default 'public_random_draw',
  conducted_by uuid references auth.users(id),
  conducted_at timestamptz not null default now(),
  notes text,
  unique(draw_version)
);

create table if not exists public.notices (
  id uuid primary key default gen_random_uuid(),
  title_en text not null,
  title_bn text,
  body_en text,
  body_bn text,
  is_published boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_settings (
  setting_key text primary key,
  setting_value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- Seed all 31 scheduled matches. Dec 11 is intentionally a rest day.
insert into public.matches(match_no,match_date,round_key)
select n,
  case
    when n <= 2 then date '2026-12-10'
    when n <= 4 then date '2026-12-12'
    when n <= 6 then date '2026-12-13'
    when n <= 8 then date '2026-12-14'
    when n <= 10 then date '2026-12-15'
    when n <= 12 then date '2026-12-16'
    when n <= 14 then date '2026-12-17'
    when n <= 16 then date '2026-12-18'
    when n <= 18 then date '2026-12-19'
    when n <= 20 then date '2026-12-20'
    when n <= 22 then date '2026-12-21'
    when n <= 24 then date '2026-12-22'
    when n <= 26 then date '2026-12-23'
    when n <= 28 then date '2026-12-24'
    when n <= 30 then date '2026-12-25'
    else date '2026-12-26'
  end,
  case
    when n <= 16 then 'round32'
    when n <= 24 then 'round16'
    when n <= 28 then 'quarter_final'
    when n <= 30 then 'semi_final'
    else 'final'
  end
from generate_series(1,31) as n
on conflict (match_no) do nothing;

